/**
 * Unit tests for the CRC-32C implementations.
 *
 * Every implementation (the dispatching crc32c(), the software version and,
 * where supported, the hardware versions) is tested individually against
 * the expected values. The expected values come from:
 *
 *   - Published test vectors (RFC 3720 appendix B.4 and the standard
 *     "123456789" check value).
 *   - A trivial bit-by-bit reference implementation in this file, which
 *     shares no code or tables with the implementations under test, and
 *     which is itself validated against the published test vectors.
 *
 * The input data is generated by a fully specified pseudo random generator
 * so that the input (and thus the expected values) is identical on all
 * platforms regardless of endianness.
 */

#include <fmt/format.h>
#include <folly/portability/GTest.h>
#include <platform/crc32c.h>

#include <array>
#include <cstddef>
#include <cstdint>
#include <cstring>
#include <ostream>
#include <span>
#include <string>
#include <string_view>
#include <vector>

/** Short (3-way) block size used by the implementations. */
static constexpr size_t ShortBlock = 256;
/** Long (3-way) block size used by the implementations. */
static constexpr size_t LongBlock = 8192;
/** Size of the generated test pattern (1 MiB). */
static constexpr size_t PatternSize = 1024 * 1024;
/**
 * The maximum misalignment to test. 16 covers both the 8 byte alignment
 * used by the software and x86/AArch64 code and the 16 byte alignment used
 * by the s390x vector code.
 */
static constexpr size_t MaxOffset = 16;
/** Lengths up to (and including) this are tested exhaustively. */
static constexpr size_t ExhaustiveLength = (6 * ShortBlock) + 128;

/** The well known CRC-32C check value for the ASCII string "123456789". */
static constexpr uint32_t CheckValue = 0xe3069283;

using Crc32cFunction = uint32_t (*)(const uint8_t*, size_t, uint32_t);

/** An implementation under test. */
struct Implementation {
    std::string name;
    Crc32cFunction function;
};

/** Make gtest print the name of the implementation in failure messages. */
static void PrintTo(const Implementation& implementation, std::ostream* os) {
    *os << implementation.name;
}

/** A test vector with its expected CRC-32C. */
struct TestVector {
    std::string name;
    std::vector<uint8_t> data;
    uint32_t expected;
};

static std::string toHex(uint32_t value) {
    return fmt::format("{:#010x}", value);
}

/**
 * Bit-by-bit CRC-32C reference implementation.
 *
 * Intentionally as simple as possible (and slow) so that it is easy to
 * verify by inspection.
 *
 * @param data the data to calculate the checksum over
 * @param crc_in the CRC of the preceding data (0 for a new checksum)
 * @return the CRC-32C of the data
 */
static uint32_t referenceCrc32c(std::span<const uint8_t> data,
                                uint32_t crc_in = 0) {
    constexpr uint32_t polynomial = 0x82f63b78; // reflected 0x1edc6f41
    uint32_t crc = ~crc_in;
    for (const auto byte : data) {
        crc ^= byte;
        for (int bit = 0; bit < 8; ++bit) {
            crc = (crc & 1) ? (crc >> 1) ^ polynomial : crc >> 1;
        }
    }
    return ~crc;
}

/** Return the bytes of the given string. */
static std::vector<uint8_t> toBytes(std::string_view text) {
    return {text.begin(), text.end()};
}

/**
 * Generate the test pattern using xorshift32 with a fixed seed. Only fixed
 * width unsigned arithmetic is used, so the output is identical on all
 * platforms.
 */
static std::vector<uint8_t> generatePattern(size_t size) {
    std::vector<uint8_t> pattern(size);
    uint32_t state = 0x12345678;
    for (auto& byte : pattern) {
        state ^= state << 13;
        state ^= state >> 17;
        state ^= state << 5;
        byte = static_cast<uint8_t>(state >> 24);
    }
    return pattern;
}

/** The test vectors from RFC 3720 appendix B.4 plus the "check" value. */
static std::vector<TestVector> publishedTestVectors() {
    std::vector<TestVector> vectors;

    vectors.push_back({.name = "123456789",
                       .data = toBytes("123456789"),
                       .expected = CheckValue});
    vectors.push_back({.name = "32 bytes of zeros",
                       .data = std::vector<uint8_t>(32, 0x00),
                       .expected = 0x8a9136aa});
    vectors.push_back({.name = "32 bytes of ones",
                       .data = std::vector<uint8_t>(32, 0xff),
                       .expected = 0x62a8ab43});

    std::vector<uint8_t> incrementing(32);
    for (size_t ii = 0; ii < incrementing.size(); ++ii) {
        incrementing[ii] = static_cast<uint8_t>(ii);
    }
    vectors.push_back({.name = "32 incrementing bytes",
                       .data = incrementing,
                       .expected = 0x46dd794e});

    std::vector<uint8_t> decrementing(32);
    for (size_t ii = 0; ii < decrementing.size(); ++ii) {
        decrementing[ii] = static_cast<uint8_t>(31 - ii);
    }
    vectors.push_back({.name = "32 decrementing bytes",
                       .data = decrementing,
                       .expected = 0x113fdb5c});

    vectors.push_back({.name = "iSCSI SCSI read (10) command PDU",
                       .data = {0x01, 0xc0, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
                                0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
                                0x14, 0x00, 0x00, 0x00, 0x00, 0x00, 0x04, 0x00,
                                0x00, 0x00, 0x00, 0x14, 0x00, 0x00, 0x00, 0x18,
                                0x28, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
                                0x02, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00},
                       .expected = 0xd9963a56});
    return vectors;
}

/**
 * Lengths of particular interest beyond the exhaustively tested range;
 * around the 3 x LongBlock boundary of the long block code path and the
 * full pattern size.
 */
static std::vector<size_t> interestingLengths() {
    std::vector<size_t> lengths;
    for (const size_t base : {3 * LongBlock, 6 * LongBlock}) {
        for (const size_t delta : {0, 1, 7, 8, 9, 15, 16, 17, 63, 64, 65}) {
            lengths.push_back(base - delta);
            lengths.push_back(base + delta);
        }
    }
    lengths.push_back((3 * LongBlock) + (3 * ShortBlock) + 65);
    lengths.push_back((6 * LongBlock) + (3 * ShortBlock) + 65);
    lengths.push_back(PatternSize - 1);
    lengths.push_back(PatternSize);
    return lengths;
}

/**
 * A copy of some data placed at a given offset from a 64 byte aligned
 * address, so that tests control the (mis)alignment seen by the code.
 */
class AlignedCopy {
public:
    AlignedCopy(std::span<const uint8_t> source, size_t offset)
        : storage(source.size() + offset + 64) {
        const auto address = reinterpret_cast<uintptr_t>(storage.data());
        const auto aligned = (address + 63) & ~uintptr_t{63};
        data = storage.data() + (aligned - address) + offset;
        std::memcpy(data, source.data(), source.size());
    }

    const uint8_t* get() const {
        return data;
    }

private:
    std::vector<uint8_t> storage;
    uint8_t* data = nullptr;
};

/** All the implementations which may be called on this platform. */
static std::vector<Implementation> implementations() {
    std::vector<Implementation> ret;
    ret.push_back({.name = "dispatch", .function = crc32c});
    ret.push_back({.name = "sw", .function = crc32c_sw});
#ifdef CB_CRC32_HW_SUPPORTED
    ret.push_back({.name = "hw", .function = crc32c_hw});
    ret.push_back({.name = "hw_1way", .function = crc32c_hw_1way});
#endif
    return ret;
}

/** Validate the reference implementation before relying on it. */
TEST(Crc32cReference, PublishedTestVectors) {
    for (const auto& vector : publishedTestVectors()) {
        EXPECT_EQ(toHex(vector.expected), toHex(referenceCrc32c(vector.data)))
                << vector.name;
    }
}

/**
 * Pin the pattern and its checksum. The values were computed with an
 * independent implementation; a failure here means that the pattern
 * generator (not the CRC code) behaves differently on this platform.
 */
TEST(Crc32cReference, Pattern) {
    const auto pattern = generatePattern(PatternSize);
    ASSERT_EQ(0x87, pattern[0]);
    ASSERT_EQ(0x15, pattern[1]);
    ASSERT_EQ(0xc9, pattern[PatternSize - 1]);
    EXPECT_EQ(toHex(0xa8f7b6ff), toHex(referenceCrc32c(pattern)));
}

class Crc32cTest : public ::testing::TestWithParam<Implementation> {
protected:
    void SetUp() override {
        pattern = generatePattern(PatternSize);
        // prefixCrc[len] is the CRC of the first len bytes of the pattern.
        prefixCrc.resize(PatternSize + 1);
        prefixCrc[0] = 0;
        for (size_t ii = 0; ii < PatternSize; ++ii) {
            prefixCrc[ii + 1] =
                    referenceCrc32c({pattern.data() + ii, 1}, prefixCrc[ii]);
        }
    }

    uint32_t calculate(const uint8_t* buf, size_t len, uint32_t crc_in = 0) {
        return GetParam().function(buf, len, crc_in);
    }

    /**
     * Verify the checksum of the first len bytes of the pattern placed in
     * the buffer. To avoid flooding the output if an implementation is
     * completely broken, only the first few failures are reported.
     *
     * @return true if the checksum was correct
     */
    bool verifyPrefix(const AlignedCopy& copy, size_t offset, size_t len) {
        const auto actual = calculate(copy.get(), len);
        if (actual == prefixCrc[len]) {
            return true;
        }
        if (++failures <= MaxReportedFailures) {
            ADD_FAILURE() << "len:" << len << " offset:" << offset
                          << " expected:" << toHex(prefixCrc[len])
                          << " actual:" << toHex(actual);
        }
        return false;
    }

    static constexpr int MaxReportedFailures = 10;
    int failures = 0;

    std::vector<uint8_t> pattern;
    std::vector<uint32_t> prefixCrc;
};

TEST_P(Crc32cTest, PublishedTestVectors) {
    for (const auto& vector : publishedTestVectors()) {
        for (size_t offset = 0; offset < MaxOffset; ++offset) {
            const AlignedCopy copy(vector.data, offset);
            EXPECT_EQ(toHex(vector.expected),
                      toHex(calculate(copy.get(), vector.data.size())))
                    << vector.name << " offset:" << offset;
        }
    }
}

TEST_P(Crc32cTest, EmptyInputReturnsCrcIn) {
    const std::array<uint8_t, 1> buffer{{0}};
    EXPECT_EQ(toHex(0), toHex(calculate(buffer.data(), 0, 0)));
    EXPECT_EQ(toHex(CheckValue),
              toHex(calculate(buffer.data(), 0, CheckValue)));
    EXPECT_EQ(toHex(0xffffffff),
              toHex(calculate(buffer.data(), 0, 0xffffffff)));
}

/**
 * Test every length up to ExhaustiveLength at every offset. This covers
 * the byte-by-byte head and tail handling, the 8 byte loop and the short
 * block code path (and the transitions between them).
 */
TEST_P(Crc32cTest, AllShortLengthsAndOffsets) {
    for (size_t offset = 0; offset < MaxOffset; ++offset) {
        const AlignedCopy copy({pattern.data(), ExhaustiveLength}, offset);
        for (size_t len = 0; len <= ExhaustiveLength; ++len) {
            verifyPrefix(copy, offset, len);
        }
    }
    EXPECT_EQ(0, failures) << "failures in total";
}

/** Test lengths around the long block boundaries at every offset. */
TEST_P(Crc32cTest, LongLengthsAndOffsets) {
    for (size_t offset = 0; offset < MaxOffset; ++offset) {
        const AlignedCopy copy(pattern, offset);
        for (const auto len : interestingLengths()) {
            verifyPrefix(copy, offset, len);
        }
    }
    EXPECT_EQ(0, failures) << "failures in total";
}

/**
 * Calculating the CRC of A followed by B by passing the CRC of A as crc_in
 * must be the same as calculating the CRC of A and B in one go.
 */
TEST_P(Crc32cTest, IncrementalTwoParts) {
    const auto* data = pattern.data();
    for (const size_t total : {size_t{0},
                               size_t{1},
                               size_t{9},
                               size_t{64},
                               (3 * ShortBlock) + 65,
                               (6 * ShortBlock) + 1,
                               (3 * LongBlock) + (3 * ShortBlock) + 65}) {
        std::vector<size_t> splits;
        if (total <= (6 * ShortBlock) + 1) {
            for (size_t split = 0; split <= total; ++split) {
                splits.push_back(split);
            }
        } else {
            for (const size_t split : {size_t{0},
                                       size_t{1},
                                       size_t{7},
                                       size_t{8},
                                       3 * ShortBlock,
                                       (3 * ShortBlock) + 1,
                                       LongBlock - 1,
                                       3 * LongBlock,
                                       total - 1,
                                       total}) {
                splits.push_back(split);
            }
        }

        for (const auto split : splits) {
            const auto first = calculate(data, split);
            const auto actual = calculate(data + split, total - split, first);
            if (actual != prefixCrc[total] &&
                ++failures <= MaxReportedFailures) {
                ADD_FAILURE() << "total:" << total << " split:" << split
                              << " expected:" << toHex(prefixCrc[total])
                              << " actual:" << toHex(actual);
            }
        }
    }
    EXPECT_EQ(0, failures) << "failures in total";
}

/** Calculate the CRC of the entire pattern in chunks of varying size. */
TEST_P(Crc32cTest, IncrementalManyChunks) {
    constexpr std::array<size_t, 12> chunkSizes{{1,
                                                 3,
                                                 8,
                                                 15,
                                                 64,
                                                 255,
                                                 3 * ShortBlock,
                                                 (3 * ShortBlock) + 1,
                                                 4097,
                                                 3 * LongBlock,
                                                 (3 * LongBlock) + 13,
                                                 0}};
    uint32_t crc = 0;
    size_t position = 0;
    size_t index = 0;
    while (position < PatternSize) {
        const auto len = std::min(chunkSizes[index++ % chunkSizes.size()],
                                  PatternSize - position);
        crc = calculate(pattern.data() + position, len, crc);
        position += len;
        ASSERT_EQ(toHex(prefixCrc[position]), toHex(crc))
                << "position:" << position << " chunk:" << len;
    }
}

/** Continue a checksum from a published value. */
TEST_P(Crc32cTest, IncrementalPublishedValue) {
    const auto data = toBytes("123456789");
    for (size_t split = 0; split <= data.size(); ++split) {
        const auto first = calculate(data.data(), split);
        EXPECT_EQ(toHex(CheckValue),
                  toHex(calculate(
                          data.data() + split, data.size() - split, first)))
                << "split:" << split;
    }
}

INSTANTIATE_TEST_SUITE_P(Crc32c,
                         Crc32cTest,
                         ::testing::ValuesIn(implementations()),
                         [](const auto& info) { return info.param.name; });

/** Mixing implementations within one checksum must give the same result. */
TEST(Crc32cMixed, AlternateImplementations) {
    const auto impls = implementations();
    const auto pattern = generatePattern(4 * LongBlock);
    const auto expected = referenceCrc32c(pattern);
    for (const size_t chunk : {size_t{1},
                               size_t{7},
                               size_t{100},
                               size_t{777},
                               (3 * ShortBlock) + 3,
                               LongBlock + 1}) {
        uint32_t crc = 0;
        size_t position = 0;
        size_t index = 0;
        while (position < pattern.size()) {
            const auto len = std::min(chunk, pattern.size() - position);
            crc = impls[index++ % impls.size()].function(
                    pattern.data() + position, len, crc);
            position += len;
        }
        EXPECT_EQ(toHex(expected), toHex(crc)) << "chunk:" << chunk;
    }
}

TEST(Crc32cStringView, CheckValue) {
    EXPECT_EQ(toHex(CheckValue), toHex(crc32c(std::string_view{"123456789"})));
    EXPECT_EQ(toHex(CheckValue),
              toHex(crc32c(std::string_view{"6789"},
                           crc32c(std::string_view{"12345"}))));
    EXPECT_EQ(toHex(0), toHex(crc32c(std::string_view{})));
}
